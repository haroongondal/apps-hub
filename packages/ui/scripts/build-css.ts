import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

import { brands, fonts, palette, radius, space, type, type BrandKey, type Palette, type Scheme } from '../src/tokens.ts';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const vars = (p: Palette) => Object.entries(p).map(([k, v]) => `  --c-${kebab(k)}: ${v};`).join('\n');

export function buildCss(): string {
  const out: string[] = ['/* Generated by packages/ui/scripts/build-css.ts from src/tokens.ts. Do not edit. */', ''];
  const faces: Array<[string, string, number]> = [
    ['Atkinson Hyperlegible Next', fonts.regular, 400],
    ['Atkinson Hyperlegible Next', fonts.semibold, 600],
    ['Atkinson Hyperlegible Next', fonts.heavy, 800],
    ['Atkinson Hyperlegible Mono', fonts.mono, 400],
    ['Atkinson Hyperlegible Mono', fonts.monoSemibold, 600],
  ];
  for (const [family, file, weight] of faces) {
    out.push(`@font-face { font-family: '${family}'; src: url('../fonts/${file}.ttf') format('truetype'); font-weight: ${weight}; font-display: swap; }`);
  }
  out.push('', ':root {');
  out.push(`  --font-sans: 'Atkinson Hyperlegible Next', system-ui, -apple-system, 'Segoe UI', sans-serif;`);
  out.push(`  --font-mono: 'Atkinson Hyperlegible Mono', ui-monospace, 'SF Mono', Menlo, monospace;`);
  for (const [k, v] of Object.entries(space)) out.push(`  --space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(radius)) out.push(`  --radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(type)) out.push(`  --type-${kebab(k)}: ${v.size}px/${v.lineHeight}px;`);
  out.push('}');
  for (const brand of Object.keys(brands) as BrandKey[]) {
    const block = (scheme: Scheme) => vars(palette(brand, scheme));
    out.push('', `[data-brand='${brand}'], [data-brand='${brand}'][data-theme='light'] {`, '  color-scheme: light;', block('light'), '}');
    out.push(`@media (prefers-color-scheme: dark) {`, `  [data-brand='${brand}']:not([data-theme='light']) {`, '  color-scheme: dark;', block('dark'), '  }', '}');
    out.push(`[data-brand='${brand}'][data-theme='dark'] {`, '  color-scheme: dark;', block('dark'), '}');
  }
  return out.join('\n') + '\n';
}

export const cssPath = fileURLToPath(new URL('../web/tokens.css', import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(cssPath, buildCss());
  console.log(`wrote ${cssPath}`);
}
